export function getTranslation(langCode: string, key: string, fallback: any = ''): any {
  const lang = UI_STRINGS[langCode] || UI_STRINGS['en'];
  const keys = key.split('.');
  let val: any = lang;
  for (const k of keys) {
    if (val && typeof val === 'object') {
      val = val[k];
    } else {
      val = undefined;
      break;
    }
  }
  if (val !== undefined) return val;
  // Fallback to English
  let enVal: any = UI_STRINGS['en'];
  for (const k of keys) {
    if (enVal && typeof enVal === 'object') {
      enVal = enVal[k];
    } else {
      enVal = undefined;
      break;
    }
  }
  return enVal !== undefined ? enVal : fallback;
}

